/** The report's words in [lang] (the report follows the UI language). */
export function bugReportLabels(lang: Lang): BugReportLabels {
  const r = (key: string, params?: Record<string, string | number>) => translate(lang, `report.md.${key}`, params);
  return {
    title: r('title'),
    titleFor: (what) => r('titleFor', { what }),
    note: r('note'),
    environment: r('environment'),
    moment: r('moment'),
    window: (from, to) => r('window', { from, to }),
    windowCut: r('windowCut'),
    device: r('device'),
    app: r('app'),
    sdk: r('sdk'),
    sdkNone: r('sdkNone'),
    durbun: r('durbun'),
    scopeAll: r('scopeAll'),
    theMoment: r('theMoment'),
    failedRequests: (count) => r('failedRequests', { count }),
    moreRequests: (count) => r('moreRequests', { count }),
    noFailedRequests: r('noFailedRequests'),
    logLines: (count) => r('logLines', { count }),
    lastLines: (shown, total) => r('lastLines', { shown, total }),
    linesCut: (count) => r('linesCut', { count }),
    noLogLines: r('noLogLines'),
    allLinesInZip: r('allLinesInZip'),
    attachments: r('attachments'),
    attLogs: (count) => r('attLogs', { count }),
    attHar: (count) => r('attHar', { count }),
    attScreenshot: r('attScreenshot'),
    attCrash: r('attCrash'),
    attRecording: r('attRecording'),
    masked: r('masked'),
    raw: r('raw'),
    failed: r('failed'),
  };
}

/** "30 sn", "2 dk", "yok": a window length in the UI language. */
export function durationLabel(lang: Lang, seconds: number): string {
  if (seconds <= 0) return translate(lang, 'report.dur.zero');
  return seconds % 60 === 0 ? translate(lang, 'report.dur.m', { count: seconds / 60 }) : translate(lang, 'report.dur.s', { count: seconds });
}
