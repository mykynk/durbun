/** Localized text of a query error (falls back to the English message). */
export function queryErrorText(error: QueryError | undefined | null): string {
  if (!error) return '';
  if (!error.messageKey || !hasMessage(error.messageKey)) return error.message;
  return t(error.messageKey, error.messageParams);
}
